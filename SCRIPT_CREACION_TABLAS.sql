CREATE TABLE ESTATUS_EMPLEADOS (
  ID_ESTATUS VARCHAR2(20) CONSTRAINT PK_ESTATUS_EMPLEADOS PRIMARY KEY,
  DESCRIPCION VARCHAR2(100) NOT NULL CONSTRAINT UK_ESTATUS_EMPLEADOS_DESC UNIQUE
);

CREATE TABLE SEXOS (
  ID_SEXO CHAR(3) CONSTRAINT PK_SEXOS PRIMARY KEY,
  DESCRIPCION VARCHAR2(20) NOT NULL CONSTRAINT UK_SEXOS_DESC UNIQUE
);

CREATE TABLE PAISES (
  ID_PAIS VARCHAR2(3) CONSTRAINT PK_PAISES PRIMARY KEY,
  NOMBRE VARCHAR2(50) NOT NULL CONSTRAINT UK_PAISES_NOMBRE UNIQUE
);

CREATE TABLE ESTADOS (
  ID_ESTADO VARCHAR2(5) CONSTRAINT PK_ESTADOS PRIMARY KEY,
  NOMBRE VARCHAR2(50) NOT NULL,
  ID_PAIS VARCHAR2(3) NOT NULL,
  CONSTRAINT FK_ESTADOS_PAISES FOREIGN KEY (ID_PAIS) REFERENCES PAISES(ID_PAIS),
  CONSTRAINT UK_ESTADOS_PAIS_NOMBRE UNIQUE (ID_PAIS, NOMBRE)
);

CREATE TABLE DEPARTAMENTOS (
  ID_DEPTO NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_DEPARTAMENTOS PRIMARY KEY,
  DESCRIPCION VARCHAR2(100) NOT NULL CONSTRAINT UK_DEPARTAMENTOS_DESC UNIQUE
);

CREATE TABLE PUESTOS (
  ID_PUESTO NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_PUESTOS PRIMARY KEY,
  DESCRIPCION_PUESTO VARCHAR2(100) NOT NULL CONSTRAINT UK_PUESTOS_DESC UNIQUE
);

CREATE TABLE EMPLEADOS (
  ID_EMPLEADO NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_EMPLEADOS PRIMARY KEY,
  NOMBRE VARCHAR2(50) NOT NULL,
  APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
  APELLIDO_MATERNO VARCHAR2(50),
  FECHA_NACIMIENTO DATE NOT NULL,
  CORREO_INSTITUCIONAL VARCHAR2(100) NOT NULL,
  TELEFONO_CELULAR VARCHAR2(15) NOT NULL,
  FECHA_INGRESO DATE DEFAULT SYSDATE NOT NULL,
  ID_SEXO CHAR(3) NOT NULL,
  ID_DEPTO NUMBER NOT NULL,
  ID_PUESTO NUMBER NOT NULL,
  ID_ESTATUS VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,
  CONSTRAINT UK_EMPLEADOS_CORREO UNIQUE (CORREO_INSTITUCIONAL),
  CONSTRAINT UK_EMPLEADOS_TELEFONO UNIQUE (TELEFONO_CELULAR),
  CONSTRAINT CK_EMPLEADOS_TELEFONO CHECK (REGEXP_LIKE(TELEFONO_CELULAR, '^[0-9]{10}$')),
  CONSTRAINT CK_EMPLEADOS_CORREO CHECK (REGEXP_LIKE(CORREO_INSTITUCIONAL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
  CONSTRAINT CK_EMPLEADOS_NACIMIENTO CHECK (FECHA_NACIMIENTO >= DATE '1900-01-01'),
  CONSTRAINT CK_EMPLEADOS_FECHAS CHECK (FECHA_INGRESO >= FECHA_NACIMIENTO),
  CONSTRAINT FK_EMPLEADOS_SEXOS FOREIGN KEY (ID_SEXO) REFERENCES SEXOS(ID_SEXO),
  CONSTRAINT FK_EMPLEADOS_DEPTOS FOREIGN KEY (ID_DEPTO) REFERENCES DEPARTAMENTOS(ID_DEPTO),
  CONSTRAINT FK_EMPLEADOS_PUESTOS FOREIGN KEY (ID_PUESTO) REFERENCES PUESTOS(ID_PUESTO),
  CONSTRAINT FK_EMPLEADOS_ESTATUS FOREIGN KEY (ID_ESTATUS) REFERENCES ESTATUS_EMPLEADOS(ID_ESTATUS)
);

CREATE TABLE DOMICILIOS (
  ID_EMPLEADO NUMBER CONSTRAINT PK_DOMICILIOS PRIMARY KEY,
  CALLE VARCHAR2(100) NOT NULL,
  CODIGO_POSTAL VARCHAR2(5) NOT NULL,
  NUMERO_EXTERIOR VARCHAR2(10) NOT NULL,
  NUMERO_INTERIOR VARCHAR2(10),
  ID_ESTADO VARCHAR2(5) NOT NULL,
  CONSTRAINT CK_DOMICILIOS_CP CHECK (REGEXP_LIKE(CODIGO_POSTAL, '^[0-9]{5}$')),
  CONSTRAINT FK_DOMICILIOS_EMPLEADOS FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS(ID_EMPLEADO),
  CONSTRAINT FK_DOMICILIOS_ESTADOS FOREIGN KEY (ID_ESTADO) REFERENCES ESTADOS(ID_ESTADO)
);

CREATE TABLE CREDENCIALES (
  ID_EMPLEADO NUMBER CONSTRAINT PK_CREDENCIALES PRIMARY KEY,
  USUARIO VARCHAR2(30) NOT NULL CONSTRAINT UK_CREDENCIALES_USUARIO UNIQUE,
  CONTRASENA_HASH VARCHAR2(255) NOT NULL,
  CONSTRAINT FK_CREDENCIALES_EMPLEADOS FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS(ID_EMPLEADO)
);

-- Registro de cursos de cada empleado, no un catalogo.
-- Se conserva una PK propia: un empleado puede cursar varios cursos o repetir uno.
CREATE TABLE EMPLEADO_CURSOS (
  ID_EMPLEADO_CURSO NUMBER GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_EMPLEADO_CURSOS PRIMARY KEY,
  ID_EMPLEADO NUMBER NOT NULL,
  NOMBRE_CURSO VARCHAR2(150) NOT NULL,
  DESCRIPCION VARCHAR2(250),
  FECHA_INICIO DATE DEFAULT SYSDATE NOT NULL,
  FECHA_FIN DATE,
  CONSTANCIA VARCHAR2(500),
  CONSTRAINT FK_EMPCURSOS_EMPLEADOS FOREIGN KEY (ID_EMPLEADO) REFERENCES EMPLEADOS(ID_EMPLEADO),
  CONSTRAINT CK_EMPCURSOS_FECHAS CHECK (FECHA_FIN IS NULL OR FECHA_FIN >= FECHA_INICIO)
);